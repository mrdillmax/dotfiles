#!/usr/bin/env bash
# Generate docs/modules.md from modules/*/module.conf.
#
# module.conf is the single source of truth: this table cannot drift from the
# files because tests/style.sh runs `modules-doc.sh --check`.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/docs/modules.md"
CHECK=0

case "${1:-}" in
    --check) CHECK=1 ;;
    '') ;;
    *)
        printf 'Usage: %s [--check]\n' "$(basename "$0")" >&2
        exit 2
        ;;
esac

# Print one tab-separated row: description, packages, services, requires.
read_conf() {
    bash -c '
        source "$1"
        printf "%s\t" "$DESCRIPTION"
        printf "%s " "${PACKAGES[@]}"; printf "\t"
        printf "%s " "${SERVICES[@]}"; printf "\t"
        printf "%s " "${REQUIRES[@]}"; printf "\t"
        printf "%s" "${OPTIONAL:-0}"; printf "\n"
    ' _ "$1"
}

generate() {
    printf '# Modules\n\n'
    # shellcheck disable=SC2016 # backticks are Markdown, not subshells.
    printf 'Generated by `scripts/modules-doc.sh` from each `modules/*/module.conf`.\n'
    printf 'Do not edit this file by hand.\n\n'
    printf '| Module | Purpose | Packages | Binaries |\n'
    printf '|--------|---------|----------|----------|\n'

    local conf dir module purpose packages _services _requires optional binaries file names
    for conf in "$ROOT"/modules/*/module.conf; do
        dir="$(dirname "$conf")"
        module="$(basename "$dir")"
        IFS=$'\t' read -r purpose packages _services _requires optional < <(read_conf "$conf")
        [[ ${optional:-0} == 1 ]] && purpose+=" (optional)"
        packages="$(printf '%s' "$packages" | tr ' ' '\n' | awk 'NF' | paste -sd, - | sed 's/,/, /g')"
        names=()
        if [[ -d $dir/home/.local/bin ]]; then
            while IFS= read -r file; do
                names+=("$(basename "$file")")
            done < <(find "$dir/home/.local/bin" -maxdepth 1 -type f | sort)
        fi
        binaries="$(printf '%s' "${names[*]}" | tr ' ' '\n' | awk 'NF' | paste -sd, - | sed 's/,/, /g')"
        # shellcheck disable=SC2016 # backticks are Markdown.
        printf '| `%s` | %s | %s | %s |\n' \
            "$module" "${purpose:-—}" "${packages:-—}" "${binaries:-—}"
    done
}

if ((CHECK)); then
    tmp="$(mktemp)"
    trap 'rm -f "$tmp"' EXIT
    generate >"$tmp"
    if ! diff -u "$OUT" "$tmp" >/dev/null 2>&1; then
        printf 'docs/modules.md is stale; run scripts/modules-doc.sh\n' >&2
        diff -u "$OUT" "$tmp" >&2 || true
        exit 1
    fi
    exit 0
fi

generate >"$OUT"
printf 'wrote %s\n' "${OUT#"$ROOT"/}"
