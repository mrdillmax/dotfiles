#!/usr/bin/env bash
# Tests for modules/idle. All writes go to a temporary home; pkill is stubbed.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCRIPT="$ROOT/modules/idle/home/.local/bin/idle-tune.sh"
PASS=0
FAIL=0
TMP_DIRS=()

cleanup() {
    local d
    for d in "${TMP_DIRS[@]}"; do
        rm -rf -- "$d"
    done
}
trap cleanup EXIT

pass() { PASS=$((PASS + 1)); printf 'PASS %s\n' "$*"; }
fail() { FAIL=$((FAIL + 1)); printf 'FAIL %s\n' "$*"; }

base="$(mktemp -d)"
TMP_DIRS+=("$base")
home="$base/home"
state="$base/state"
config="$base/config"
bin="$base/bin"
pkill_log="$base/pkill.log"
hypridle_marker="$base/hypridle.started"

mkdir -p "$home" "$state" "$config" "$bin"
: >"$pkill_log"

cat >"$bin/pkill" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"$IDLE_PKILL_LOG"
exit 0
EOF
cat >"$bin/pgrep" <<'EOF'
#!/usr/bin/env bash
exit 1
EOF

cat >"$bin/hypridle" <<'EOF'
#!/usr/bin/env bash
: >"$HYPRIDLE_MARKER"
EOF
chmod 0755 "$bin/pkill" "$bin/pgrep" "$bin/hypridle"

state_file="$state/dotfiles/idle.conf"
hypridle_conf="$config/hypr/hypridle.conf"

run_idle() {
    env HOME="$home" XDG_STATE_HOME="$state" XDG_CONFIG_HOME="$config" \
        PATH="$bin:$PATH" IDLE_POWER="${IDLE_POWER:-battery}" \
        IDLE_PKILL_LOG="$pkill_log" HYPRIDLE_MARKER="$hypridle_marker" \
        bash "$SCRIPT" "$@"
}

# 1. Help.
if run_idle --help >/dev/null 2>&1; then
    pass "--help exits 0"
else
    fail "--help failed"
fi

# 2. Defaults and power detection.
status_out="$(run_idle status)"
if grep -qx 'battery: dim=150 lock=300 off=330 suspend=900' <<<"$status_out" \
    && grep -qx 'ac:      dim=300 lock=600 off=660 suspend=1800' <<<"$status_out"; then
    pass "defaults match the battery and AC profiles"
else
    fail "defaults are wrong"
    printf '%s\n' "$status_out"
fi
if grep -qx 'power: battery' <<<"$status_out"; then
    pass "status reports the battery profile"
else
    fail "power detection is wrong"
fi
if grep -qx 'enabled: 0' <<<"$status_out"; then
    pass "idle is disabled by default"
else
    fail "the enabled state is missing"
fi

# 2b. Disable and re-enable idle.
run_idle disable >/dev/null
if grep -qx 'ENABLED=0' "$state_file"; then
    pass "disable persists the off state"
else
    fail "disable did not persist the off state"
fi
if run_idle run | grep -q 'idle is disabled'; then
    pass "autostart run respects the disabled state"
else
    fail "autostart run ignored the disabled state"
fi
run_idle enable >/dev/null
sleep 0.2
if grep -qx 'ENABLED=1' "$state_file" && [[ -e $hypridle_marker ]]; then
    pass "enable restores the state and starts hypridle"
else
    fail "enable did not start hypridle"
fi

# 3. Dry-run writes nothing.
rm -f "$state_file"
dry_out="$(run_idle apply --profile battery --dry-run)"
if grep -q 'profile=battery dim=150 lock=300 off=330 suspend=900' <<<"$dry_out" \
    && [[ ! -e $hypridle_conf && ! -e $state_file ]] \
    && [[ ! -s $pkill_log ]]; then
    pass "dry-run apply writes nothing"
else
    fail "dry-run apply changed something"
    printf '%s\n' "$dry_out"
fi

# 4. A real battery apply renders the expected listeners and reloads.
run_idle apply --profile battery >/dev/null
if [[ -r $hypridle_conf ]] \
    && grep -q '^# Generated by idle-tune.sh; profile=battery' "$hypridle_conf" \
    && grep -qx '    timeout = 150' "$hypridle_conf" \
    && grep -qx '    timeout = 300' "$hypridle_conf" \
    && grep -qx '    timeout = 330' "$hypridle_conf" \
    && grep -qx '    timeout = 900' "$hypridle_conf"; then
    pass "a battery apply renders 150/300/330/900"
else
    fail "the battery config is wrong"
    cat "$hypridle_conf" 2>/dev/null
fi
if grep -q -- '-USR1 -x hypridle' "$pkill_log"; then
    pass "apply asks hypridle to reload"
else
    fail "apply did not reload hypridle"
fi

# 5. Switching to AC backs up the previous config.
run_idle apply --profile ac >/dev/null
if grep -q '^# Generated by idle-tune.sh; profile=ac' "$hypridle_conf" \
    && grep -qx '    timeout = 1800' "$hypridle_conf"; then
    pass "an AC apply renders 300/600/660/1800"
else
    fail "the AC config is wrong"
    cat "$hypridle_conf"
fi
backup="$(find "$state/dotfiles/idle-backup" -name 'hypridle.conf.*' -print -quit 2>/dev/null)"
if [[ -n $backup ]] && grep -q 'profile=battery' "$backup"; then
    pass "the previous config is backed up before switching"
else
    fail "no backup of the previous config was written"
fi

# 6. Auto follows the detected power source.
auto_ac="$(IDLE_POWER=ac run_idle apply --dry-run)"
auto_bat="$(IDLE_POWER=battery run_idle apply --dry-run)"
if grep -q 'profile=ac' <<<"$auto_ac" && grep -q 'profile=battery' <<<"$auto_bat"; then
    pass "auto selects AC and battery from the power source"
else
    fail "auto profile detection is wrong"
fi

# 7. set updates the state and applies the selected profile.
run_idle set --battery-dim 60 --battery-lock 120 --battery-off 180 --battery-suspend 300 >/dev/null
if grep -qx 'BATTERY_DIM=60' "$state_file" \
    && grep -qx 'BATTERY_LOCK=120' "$state_file" \
    && grep -qx 'BATTERY_OFF=180' "$state_file" \
    && grep -qx 'BATTERY_SUSPEND=300' "$state_file"; then
    pass "set stores all battery values"
else
    fail "set did not store the battery values"
    cat "$state_file" 2>/dev/null
fi
if grep -qx '    timeout = 60' "$hypridle_conf" \
    && grep -qx '    timeout = 300' "$hypridle_conf"; then
    pass "set applies the new values"
else
    fail "set did not apply the new values"
    cat "$hypridle_conf"
fi

# 8. A partial set keeps the untouched values.
run_idle set --battery-suspend 400 >/dev/null
if grep -qx 'BATTERY_DIM=60' "$state_file" \
    && grep -qx 'BATTERY_LOCK=120' "$state_file" \
    && grep -qx 'BATTERY_OFF=180' "$state_file" \
    && grep -qx 'BATTERY_SUSPEND=400' "$state_file"; then
    pass "a partial set keeps the other values"
else
    fail "a partial set overwrote other values"
    cat "$state_file"
fi

# 9. Validation rejects bad ordering and non-numeric values.
before_state="$(sha256sum "$state_file" | awk '{print $1}')"
before_conf="$(sha256sum "$hypridle_conf" | awk '{print $1}')"

expect_fail() {
    local label="$1"
    shift
    if run_idle "$@" >/dev/null 2>&1; then
        fail "$label was accepted"
    else
        pass "$label is rejected"
    fi
}

expect_fail "dim >= lock" set --battery-dim 200 --battery-lock 200
expect_fail "lock > off" set --battery-lock 400 --battery-off 300
expect_fail "off >= suspend" set --battery-off 500 --battery-suspend 500
expect_fail "a negative value" set --battery-dim -1
expect_fail "a non-numeric value" set --battery-lock abc
expect_fail "an invalid AC profile" set --ac-dim 700 --ac-lock 600

if [[ $before_state == "$(sha256sum "$state_file" | awk '{print $1}')" ]] \
    && [[ $before_conf == "$(sha256sum "$hypridle_conf" | awk '{print $1}')" ]]; then
    pass "failed validation changes nothing"
else
    fail "failed validation still wrote state or config"
fi

# 10. 0 disables stages.
run_idle set --battery-lock 0 --battery-off 0 --battery-suspend 0 >/dev/null
listeners="$(grep -c '^listener {' "$hypridle_conf")"
if [[ $listeners == 1 ]] && ! grep -q 'systemctl suspend' "$hypridle_conf"; then
    pass "0 disables lock, screen-off and suspend"
else
    fail "0 did not disable the stages (listeners=$listeners)"
    cat "$hypridle_conf"
fi

run_idle set --battery-dim 0 >/dev/null
if ! grep -q '^listener {' "$hypridle_conf"; then
    pass "0 disables every stage"
else
    fail "zeroed stages are still present"
fi

# 11. Dry-run set changes neither state nor config.
before_state="$(sha256sum "$state_file" | awk '{print $1}')"
before_conf="$(sha256sum "$hypridle_conf" | awk '{print $1}')"
dry_set="$(run_idle set --ac-dim 45 --dry-run)"
if [[ $before_state == "$(sha256sum "$state_file" | awk '{print $1}')" ]] \
    && [[ $before_conf == "$(sha256sum "$hypridle_conf" | awk '{print $1}')" ]] \
    && grep -q '\[dry-run\]' <<<"$dry_set"; then
    pass "dry-run set changes nothing"
else
    fail "dry-run set wrote state or config"
fi

# 12. Status shows the stored values.
status_out="$(run_idle status)"
if grep -q 'battery: dim=0 lock=0 off=0 suspend=0' <<<"$status_out"; then
    pass "status reflects the stored values"
else
    fail "status does not reflect the stored values"
    printf '%s\n' "$status_out"
fi

# 13. A corrupt state value is ignored with a warning.
printf 'BATTERY_DIM=not-a-number\n' >"$state_file"
corrupt_out="$(run_idle status 2>&1)"
if grep -q 'ignoring invalid BATTERY_DIM' <<<"$corrupt_out" \
    && grep -q 'battery: dim=150' <<<"$corrupt_out"; then
    pass "a corrupt state value falls back to the default"
else
    fail "a corrupt state value was used"
    printf '%s\n' "$corrupt_out"
fi

# 14. configure without a terminal is rejected instead of hanging.
if run_idle configure </dev/null >/dev/null 2>&1; then
    fail "configure ran without a terminal"
else
    pass "configure requires a terminal"
fi

printf '\n%s: %d passed, %d failed\n' "$(basename "$0")" "$PASS" "$FAIL"
((FAIL == 0))
